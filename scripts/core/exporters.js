/* ============================================================================
   scripts/core/exporters.js  —  Files you can take away
   ----------------------------------------------------------------------------
   WHAT THIS FILE DOES
     Turns the current setup and its results into:
       • Python code for the original main.py (OpticalTable class)
       • a CSV table of results (opens in Excel / Google Sheets)
       • a Markdown report (readable text with tables)
     The drawing of the table (SVG) is made in scripts/ui/canvas.js.

   SHOULD I EDIT IT?
     No.
   ============================================================================ */

(() => {
  const fmt = OGS.fmt, norm360 = OGS.norm360;

  // 90 → "sp.pi/2", 180 → "sp.pi", 45 → "sp.pi/4"
  function piExpr(deg) {
    for (let q = 1; q <= 36; q++) {
      const p = deg * q / 180;
      if (Math.abs(p - Math.round(p)) < 1e-9) {
        const P = Math.round(p); if (!P) return '0';
        const num = P === 1 ? 'sp.pi' : P === -1 ? '-sp.pi' : `${P}*sp.pi`;
        return q === 1 ? num : `${num}/${q}`;
      }
    }
    return `sp.pi*${+deg.toFixed(6)}/180`;
  }
  // 0.7071 → "sp.sqrt(2)/2"
  function sympyReal(x) {
    if (Math.abs(x) < 1e-12) return '0';
    const e = fmt.exactParts(x), sign = x < 0 ? '-' : '';
    if (!e) return String(+x.toPrecision(12));
    const root = e.r === 1 ? '' : `sp.sqrt(${e.r})`;
    const num = e.r === 1 ? String(e.p) : (e.p === 1 ? root : `${e.p}*${root}`);
    return sign + (e.q === 1 ? num : `${num}/${e.q}`);
  }
  function sympyComplex(a) {
    const re = sympyReal(a[0]), im = sympyReal(a[1]);
    if (im === '0') return re;
    const imPart = im === '1' ? 'sp.I' : im === '-1' ? '-sp.I' : `(${im})*sp.I`;
    return re === '0' ? imPart : `(${re} + ${imPart})`;
  }

  // Optional patch for main.py that fixes the issues found in the code review.
  const MAIN_PY_PATCH = `# --- Patch for main.py: four-port beam splitters and safe table edges ---
def _Transformation(self, State):
    x, y, t, d = State.indices
    H, V, P, M = self.H, self.V, self.P, self.M
    bx, by = self.Identify_BS(State)
    slash = self.Theta_bs[bx, by] in (0, 180)
    refl = ({H[P]: V[P], V[P]: H[P], H[M]: V[M], V[M]: H[M]} if slash else
            {H[P]: V[M], V[M]: H[P], H[M]: V[P], V[P]: H[M]})[d]
    def out(dirn):
        ix, iy = {H[P]: (bx+1, by), V[P]: (bx, by+1), H[M]: (bx, by), V[M]: (bx, by)}[dirn]
        return self.A_dag[ix, iy, t+1, dirn]
    th = self.Theta[bx, by]
    ph = self.PhiH[bx, by] if d.base == H else self.PhiV[bx, by]
    return {State: sp.exp(sp.I*ph)*(sp.cos(th/2)*out(d) + sp.I*sp.sin(th/2)*out(refl))}
_orig_exclude = OpticalTable.Exclude_Detector
def _Exclude(self, Var):
    bx, by = self.Identify_BS(Var)
    if not (0 <= bx < self.Size[0] and 0 <= by < self.Size[1]):
        return True
    return _orig_exclude(self, Var)
OpticalTable.Transformation = _Transformation
OpticalTable.Exclude_Detector = _Exclude
`;

  // Notebook cell that rebuilds the current setup with the OpticalTable class.
  function python(S, sim, withPatch) {
    const L = [], M = S.model, MODELS = OGS.formulas.MODELS;
    L.push(`# ${S.title || 'Optical setup'} · generated by optics.quriosity`, 'from main import *', '');
    if (M.kernel !== 'sym') L.push(`# NOTE: the simulator uses the "${MODELS[M.kernel].name}" formula; main.py implements the Symmetric one.`);
    if (M.time === 'cw') L.push('# NOTE: continuous-wave timing is used in the simulator; main.py keeps arrival times separate.');
    if (M.stats === 'dist') L.push('# NOTE: distinguishable particles are used in the simulator; main.py treats photons as identical bosons.');
    if (M.eta < 1 || S.dets.some(d => d.eta != null && d.eta < 1)) L.push('# NOTE: detector efficiency below 1 is not modelled in main.py.');
    if (withPatch) L.push('', MAIN_PY_PATCH);
    L.push(`Size = (${S.n},${S.m})`, 'T = OpticalTable(Size)', 'A,A_dag,H,V,P,M = T.A,T.A_dag,T.H,T.V,T.P,T.M', '');
    for (let x = 0; x < S.n; x++) for (let y = 0; y < S.m; y++) {
      const nd = S.grid[x][y], label = nd.name ? `   # ${nd.name}` : '';
      if (norm360(+nd.tbs)) L.push(`T.Theta_bs[${x},${y}] = ${norm360(+nd.tbs)}`);
      if (+nd.th) L.push(`T.Theta[${x},${y}] = ${piExpr(+nd.th)}${label}`);
      if (+nd.phH) L.push(`T.PhiH[${x},${y}] = ${piExpr(+nd.phH)}`);
      if (+nd.phV) L.push(`T.PhiV[${x},${y}] = ${piExpr(+nd.phV)}`);
    }
    L.push('', `T.Detectors = [${S.dets.map(d => `A_dag[${d.x},${d.y},0,${d.k === 'h' ? 'H' : 'V'}[P]]`).join(', ')}]${S.dets.length ? '   # ' + S.dets.map(d => d.name).join(', ') : ''}`);
    const parts = [];
    if (sim && sim.states[0]) for (const [k, a] of sim.states[0]) {
      const ops = k.split('§').map(p => { const f = p.split(' '); return `A_dag[${f[2]},${f[3]},0,${f[1] === 'h' ? 'H' : 'V'}[${f[4] === '+' ? 'P' : 'M'}]]`; }).join('*');
      const c = sympyComplex(a); parts.push(c === '1' ? ops : `${c}*${ops}`);
    }
    L.push('', `Input = ${parts.join(' \\\n      + ') || '0'}`, '', `Time = ${Math.max(1, (sim?.states.length || 2) - 1)}`,
      '# Note: the "Norm" printed by main.py adds |amplitude|² without the n! factor, so it reads',
      '# below 1 when two photons share a mode (for example 0.5 for Hong–Ou–Mandel). The simulator',
      '# includes the factor, so its probabilities add up to 1.',
      'Output, Status = T.Run_Experiment(Input, Time, show_steps_t=True)', 'T.Probabilities(Output)');
    return L.join('\n') + '\n';
  }

  // Results table: one row per time step, then the final joint outcomes.
  function csv(S, sim) {
    const per = sim.states.map(st => OGS.engine.stats(st, S)), names = S.dets.map(d => d.name);
    const q = v => `"${String(v).replace(/"/g, '""')}"`;
    const rows = [['step', ...names.map(n => q(`P(${n})`)), 'in_flight', 'left_table', 'missed', 'total'].join(',')];
    per.forEach((s, t) => rows.push([t, ...names.map(n => (s.det[n] || 0).toFixed(10)), s.inflight.toFixed(10), s.exited.toFixed(10), s.lost.toFixed(10), s.total.toFixed(10)].join(',')));
    rows.push('', `${q('joint outcome (final)')},probability`);
    for (const [label, p] of per[per.length - 1].joint) rows.push(`${q(label)},${p.toFixed(10)}`);
    return rows.join('\n');
  }

  // Human-readable report with the setup, results and checks.
  function report(S, sim, modelSummary) {
    const s = OGS.engine.stats(sim.states[sim.states.length - 1], S);
    const TYPE = { bs: 'Beam splitter', mirror: 'Mirror', phase: 'Phase shifter' };
    const L = [`# ${S.title || 'Optical setup'}`, '', S.desc || '', '', `- Grid: ${S.n} × ${S.m}`, `- Model: ${modelSummary}`, `- Steps: ${sim.states.length - 1}`, `- Created: ${new Date().toLocaleString()}`,
      '', '## Components', '', '| node | type | θBS | θ | φH | φV | label |', '|---|---|---|---|---|---|---|'];
    for (let x = 0; x < S.n; x++) for (let y = 0; y < S.m; y++) {
      const nd = S.grid[x][y], t = OGS.engine.classify(nd);
      if (t !== 'empty') L.push(`| (${x},${y}) | ${TYPE[t]} | ${norm360(+nd.tbs)}° | ${nd.th}° | ${nd.phH}° | ${nd.phV}° | ${nd.name || ''} |`);
    }
    L.push('', '## Input state', '', '```', S.input, '```', '', '## Detector click probabilities', '', '| detector | edge | probability |', '|---|---|---|');
    for (const d of S.dets) L.push(`| ${d.name} | ${d.k}(${d.x},${d.y}) | ${(s.det[d.name] || 0).toFixed(6)} |`);
    L.push('', '## Joint outcomes', '', '| outcome | probability |', '|---|---|');
    for (const [label, p] of s.joint.slice(0, 40)) L.push(`| ${label} | ${p.toFixed(6)} |`);
    const checks = [...(sim.err ? [{ text: sim.err }] : []), ...sim.warnings];
    if (checks.length) { L.push('', '## Checks', ''); checks.forEach(w => L.push(`- ${w.text}`)); }
    L.push('', '## Python (main.py)', '', '```python', python(S, sim, false), '```');
    return L.join('\n');
  }

  OGS.exporters = { python, csv, report, MAIN_PY_PATCH };
})();
